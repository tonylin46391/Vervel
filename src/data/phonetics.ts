/**
 * Returns formatted KK phonetic symbols for a given word or custom KK string.
 * Strips any extra surrounding slashes and returns pure KK string.
 */
export function getKKPhonetic(word: string, customKK?: string): string {
  if (customKK && customKK.trim()) {
    return customKK.trim().replace(/^\/+|\/+$/g, '');
  }
  const cleanWord = word.trim();
  const direct = KK_PHONETICS[cleanWord] || KK_PHONETICS[cleanWord.toLowerCase()];
  if (direct) {
    return direct.replace(/^\/+|\/+$/g, '');
  }

  // Multi-word phrase fallback lookup
  const parts = cleanWord.split(/\s+/);
  if (parts.length > 1) {
    const matchedParts = parts.map(p => {
      const found = KK_PHONETICS[p] || KK_PHONETICS[p.toLowerCase()];
      return found ? found.replace(/^\/+|\/+$/g, '') : p;
    });
    return matchedParts.join(' ');
  }

  return '';
}
